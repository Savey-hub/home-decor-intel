def save(p, obj):
    with open(os.path.join(D, p), "w", encoding="utf-8") as f:
        json.dump(obj, f, ensure_ascii=False, indent=2)
    print("  saved", p)


def add_unique(lst, item, keys):
    """按 keys 组合去重追加。返回 True 表示新增。"""
    sig = tuple(item.get(k) for k in keys)
    for x in lst:
        if isinstance(x, dict) and tuple(x.get(k) for k in keys) == sig:
            x.update(item)
            return False
    lst.append(item)
    return True


